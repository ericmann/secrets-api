// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { satteri } from '@astrojs/markdown-satteri';
import { docsLinks } from './src/plugins/docs-links.mjs';
import { stripLeadingH1 } from './src/plugins/strip-leading-h1.mjs';

const siteDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(siteDir, '..');
const docsDir = path.join(repoRoot, 'docs');
const repoUrl = 'https://github.com/ericmann/secrets-api';
const repoBranch = 'main';

/**
 * Markdown files in a docs/ subdirectory, as sidebar slugs.
 * Journal entries are sorted newest first by their frontmatter `date`.
 */
function markdownIn(dir) {
	const abs = path.join(docsDir, dir);
	if (!fs.existsSync(abs)) return [];
	return fs
		.readdirSync(abs)
		.filter((f) => /\.mdx?$/.test(f))
		.map((f) => {
			const src = fs.readFileSync(path.join(abs, f), 'utf8');
			const m = src.match(/^---\n[\s\S]*?^date:\s*(\d{4}-\d{2}-\d{2})\s*$[\s\S]*?^---/m);
			return { slug: `${dir}/${f.replace(/\.mdx?$/, '')}`, date: m ? m[1] : '' };
		});
}

/**
 * A sidebar group listing every page in a docs/ subdirectory, alphabetically by
 * file name. Groups are built from explicit slugs rather than `autogenerate`
 * because Starlight resolves autogenerated directories relative to
 * src/content/docs, and this content lives in ../docs. An empty directory
 * (changelog, until the first release) renders as an empty group.
 */
function group(label, dir) {
	return {
		label,
		items: markdownIn(dir)
			.sort((a, b) => a.slug.localeCompare(b.slug))
			.map(({ slug }) => ({ slug })),
	};
}

const journal = markdownIn('journal')
	.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)))
	.map(({ slug }) => ({ slug }));

/** Copy files from site/ into the root of the build output. */
function copyToDistRoot(files) {
	return {
		name: 'copy-to-dist-root',
		hooks: {
			'astro:build:done': async ({ dir }) => {
				for (const f of files) {
					await fs.promises.copyFile(path.join(siteDir, f), path.join(fileURLToPath(dir), f));
				}
			},
		},
	};
}

export default defineConfig({
	output: 'static',
	outDir: './dist',
	trailingSlash: 'always',
	markdown: {
		processor: satteri({
			mdastPlugins: [stripLeadingH1, docsLinks({ docsDir, repoRoot, repoUrl, repoBranch })],
		}),
	},
	integrations: [
		starlight({
			title: 'Secrets API',
			description: 'WordPress Core feature plugin',
			components: {
				SiteTitle: './src/components/SiteTitle.astro',
				SocialIcons: './src/components/HeaderLinks.astro',
				Footer: './src/components/Footer.astro',
			},
			customCss: ['./src/styles/custom.css'],
			// Content lives in ../docs, so tell Starlight's Markdown pipeline to process it.
			markdown: { processedDirs: ['../docs'] },
			sidebar: [
				{ label: 'Overview', items: [{ slug: 'index' }] },
				group('Spec', 'spec'),
				group('Reference', 'reference'),
				group('Decisions', 'decisions'),
				{ label: 'Journal', items: journal },
				group('Changelog', 'changelog'),
			],
		}),
		copyToDistRoot(['_headers', '_redirects']),
	],
});
